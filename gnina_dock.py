"""
GNINA CNN Docking — Rescore top CURE compounds with deep learning
Gnina uses a convolutional neural network scoring function that often
scores 0.5-1.5 kcal/mol better than Vina on tight binders.

SETUP (run once before this script):
  Windows: Download gnina binary from https://github.com/gnina/gnina/releases
           Place gnina.exe in ./bin/gnina.exe
  Linux:   wget https://github.com/gnina/gnina/releases/latest/download/gnina
           chmod +x gnina && mv gnina ./bin/gnina

Usage:
    python gnina_dock.py
    python gnina_dock.py --exhaustiveness 32

Output:
    gnina_results.json     — all scores
    gnina_results.csv      — for comparison with Vina
"""

import os, json, subprocess, argparse, csv
from pathlib import Path

